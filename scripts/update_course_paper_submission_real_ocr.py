def replace_exact(text: str, old: str, new: str) -> str:
    if old in text:
        return text.replace(old, new, 1)
    return text


def replace_section(text: str, start_header: str, next_header: str, new_section: str) -> str:
    pattern = re.compile(
        r"(?ms)^" + re.escape(start_header) + r"\n.*?(?=^" + re.escape(next_header) + r"\n)"
    )
    if not pattern.search(text):
        raise RuntimeError(f"Section not found: {start_header} -> {next_header}")
    return pattern.sub(new_section + "\n\n", text, count=1)


