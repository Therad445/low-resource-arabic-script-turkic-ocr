def update_text(text: str) -> str:
    for old, new in REPLACEMENTS:
        text = text.replace(old, new)

    if "### 5.12 Проверка переноса на real-OCR subset" not in text:
        marker = "### 5.12 Выводы по разделу"
        if marker in text:
            text = text.replace(marker, REAL_OCR_SECTION + "\n\n### 5.13 Выводы по разделу", 1)
        else:
            raise RuntimeError("Could not find marker for inserting real-OCR section")

    return text

def main() -> None:
    for path in FILES:
        if not path.exists():
            raise FileNotFoundError(path)

        text = path.read_text(encoding="utf-8")
        updated = update_text(text)

        if updated == text:
            print(f"unchanged: {path}")
        else:
            path.write_text(updated, encoding="utf-8")
            print(f"updated: {path}")

if __name__ == "__main__":
    main()
